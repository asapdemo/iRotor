#!/usr/bin/env python3
"""Pack web_ui/index.html into Core/Src/web_ui_gz.c (minified + gzip) for the firmware.

The board sends the bytes as is with "Content-Encoding: gzip"; the browser unpacks them.
CMake runs this automatically when web_ui/index.html changes (if Python is installed);
the generated file is committed so the firmware also builds without Python.

Usage: python tools/build_web_ui.py
"""

import gzip
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "web_ui" / "index.html"
OUTPUT = ROOT / "Core" / "Src" / "web_ui_gz.c"
MAX_BYTES = 0xFFFF          # web_ui_gz_len is uint16_t


def minify(text: str) -> str:
    """Conservative: drop block comments and whole-line // comments, trim indentation, keep line breaks."""
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    lines = []
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("//"):
            continue
        lines.append(line)
    return "\n".join(lines) + "\n"


def main() -> int:
    source = SOURCE.read_text(encoding="utf-8")
    packed = gzip.compress(minify(source).encode("utf-8"), compresslevel=9, mtime=0)
    if len(packed) > MAX_BYTES:
        print(f"web UI is {len(packed)} bytes gzipped, limit {MAX_BYTES}", file=sys.stderr)
        return 1

    rows = []
    for offset in range(0, len(packed), 16):
        rows.append("  " + ", ".join(f"0x{byte:02X}" for byte in packed[offset:offset + 16]) + ",")
    OUTPUT.write_text(
        "/* Generated by tools/build_web_ui.py from web_ui/index.html -- do not edit. */\n"
        f"/* {len(source.encode('utf-8'))} bytes source -> {len(packed)} bytes gzip */\n"
        "#include <stdint.h>\n\n"
        f"const uint16_t web_ui_gz_len = {len(packed)}U;\n\n"
        "const uint8_t web_ui_gz[] =\n{\n" + "\n".join(rows) + "\n};\n",
        encoding="utf-8",
        newline="\n",
    )
    print(f"{SOURCE.relative_to(ROOT)}: {len(source.encode('utf-8'))} bytes -> {OUTPUT.relative_to(ROOT)}: {len(packed)} bytes gzip")
    return 0


if __name__ == "__main__":
    sys.exit(main())
