static void LED_SetBlinkState(uint8_t state)
{
  if (recovery_mode != 0U)
  {
    if (state != 0U)
    {
      GPIO_SetPin(LED0_GPIO_Port, LED0_Pin);
      GPIO_SetPin(LED1_GPIO_Port, LED1_Pin);
    }
    else
    {
      GPIO_ResetPin(LED0_GPIO_Port, LED0_Pin);
      GPIO_ResetPin(LED1_GPIO_Port, LED1_Pin);
    }
    return;
  }

  if (state != 0U)
  {
    GPIO_SetPin(LED0_GPIO_Port, LED0_Pin);
    GPIO_ResetPin(LED1_GPIO_Port, LED1_Pin);
  }
  else
  {
    GPIO_ResetPin(LED0_GPIO_Port, LED0_Pin);
    GPIO_SetPin(LED1_GPIO_Port, LED1_Pin);
  }
}

static uint8_t Recovery_IsRequested(void)
{
  static const uint8_t text[] = "[Starting]\n\r";
  uint8_t index;

  __HAL_UART_CLEAR_OREFLAG(&huart1);
  __HAL_UART_CLEAR_FEFLAG(&huart1);
  __HAL_UART_CLEAR_NEFLAG(&huart1);

  for (index = 0U; index < (sizeof(text) - 1U); index++)
  {
    uint8_t received;

    if (HAL_UART_Transmit(&huart1, (uint8_t *)&text[index], 1U, 10U) != HAL_OK)
    {
      return 0U;
    }

    if (HAL_UART_Receive(&huart1, &received, 1U, 10U) != HAL_OK)
    {
      return 0U;
    }

    if (received != text[index])
    {
      return 0U;
    }
  }

  return 1U;
}

